def refs(*ids):
    out = []
    for sid in ids:
        s = SRC[sid]
        out.append({"url": s["url"], "version": DOC_VERSION,
                    "section": f"{s['chapter']} {s['title']}" if s.get("chapter") else s["title"],
                    "title": s["title"], "retrieved": RETRIEVED})
    return out


def concept(code, name, area, desc, diff, feature=None):
    item = {"concept_code": code, "concept_name": name, "subject_area": area,
            "description": desc, "difficulty_level": diff}
    if feature:
        item["sql_feature"] = feature
    return item


