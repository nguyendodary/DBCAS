def structural_check(questions):
    problems = []
    seen_keys, seen_prompts = set(), {}
    for q in questions:
        key = q["key"]
        if key in seen_keys:
            problems.append(f"{key}: duplicate key")
        seen_keys.add(key)
        norm = " ".join(q["prompt"].lower().split())
        if norm in seen_prompts:
            problems.append(f"{key}: duplicate prompt of {seen_prompts[norm]}")
        seen_prompts[norm] = key
        for cc in q["concept_codes"]:
            if cc not in _CONCEPTS:
                problems.append(f"{key}: unknown concept {cc}")
        if not q.get("source_refs"):
            problems.append(f"{key}: missing source_refs")
        if not q.get("explanation"):
            problems.append(f"{key}: missing explanation")
        if not q.get("tags"):
            problems.append(f"{key}: missing tags")
        if q["question_type"] == "mcq":
            opts = q["options"]
            if len(opts) != 4 or sum(1 for o in opts if o["is_correct"]) != 1:
                problems.append(f"{key}: mcq needs 4 options with exactly 1 correct")
            texts = {o["option_text"].strip().lower() for o in opts}
            if len(texts) != 4:
                problems.append(f"{key}: duplicate option text")
        if q["question_type"] == "sql":
            dss = q["datasets"]
            if len(dss) < 2 or not any(d["is_edge_case"] for d in dss):
                problems.append(f"{key}: needs >=2 datasets incl edge")
            names = [d["dataset_name"] for d in dss]
            if len(names) != len(set(names)):
                problems.append(f"{key}: duplicate dataset names")
            for cc in q["required_concept_codes"]:
                cmap = {c["concept_code"]: c for c in CONCEPTS + CORE_CONCEPTS}
                if cmap.get(cc, {}).get("sql_feature") is None:
                    problems.append(f"{key}: required concept {cc} lacks sql_feature metadata")
        if q["question_type"] == "essay":
            rub = q["rubrics"]
            if len(rub) != 4:
                problems.append(f"{key}: rubric needs 4 levels")
            bounds = [(b["min_score"], b["max_score"]) for b in rub]
            if bounds[0][0] != 0 or bounds[-1][1] != q["points"]:
                problems.append(f"{key}: rubric bounds broken")
            for (lo1, hi1), (lo2, hi2) in zip(bounds, bounds[1:]):
                if not (lo1 <= hi1 and hi1 < lo2 <= hi2):
                    problems.append(f"{key}: rubric bounds non-monotonic")
    return problems


def execute_datasets(questions):
    """Provision each dataset in the real sandbox and embed actual results."""
    sys.path.insert(0, str(ROOT / "backend"))
    from app.config import get_settings
    from app.services.sandbox_runner import SandboxRunner
    runner = SandboxRunner(get_settings())
    done, failed = 0, []
    for q in questions:
        if q["question_type"] != "sql":
            continue
        for ds in q["datasets"]:
            schema = None
            try:
                schema = runner.provision_dataset(ds["setup_sql"])
                res = runner.execute(q["reference_answer"], schema=schema)
                if not res.success:
                    failed.append((q["key"], ds["dataset_name"], "execution failed"))
                    continue
                from decimal import Decimal
                ctypes = list(res.column_types or [])
                def cell(v, i):
                    if v is None or i >= len(ctypes):
                        return v
                    if ctypes[i] == "number":
                        d = Decimal(str(v))
                        return int(d) if d == d.to_integral_value() else float(d)
                    if ctypes[i] == "boolean":
                        return v if isinstance(v, bool) else str(v).lower() in ("t", "true", "1")
                    return v
                ds["expected_result"] = {
                    "columns": list(res.columns),
                    "rows": [[cell(v, i) for i, v in enumerate(r)] for r in res.rows],
                    "check_columns": True}
                done += 1
            except Exception as e:  # noqa: BLE001 - report all dataset failures
                failed.append((q["key"], ds["dataset_name"], str(e)[:120]))
            finally:
                if schema:
                    try:
                        runner.drop_dataset(schema)
                    except Exception:
                        pass
    return done, failed


