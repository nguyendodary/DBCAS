_AREA_SLUG = {
    "PostgreSQL Querying": "queries",
    "PostgreSQL Data Types": "data-types",
    "PostgreSQL Functions": "functions",
    "PostgreSQL Data Definition": "ddl",
    "PostgreSQL Data Manipulation": "dml",
    "PostgreSQL Concurrency": "concurrency",
    "PostgreSQL Performance": "performance",
    "PostgreSQL Security": "security",
    "PostgreSQL Server Programming": "server-programming",
    "PostgreSQL Administration": "admin",
}
_CONCEPT_AREA = {c["concept_code"]: c["subject_area"] for c in CONCEPTS}
_CONCEPTS = {c["concept_code"] for c in CONCEPTS} | {
    "SQL-SELECT", "SQL-WHERE", "SQL-JOIN", "SQL-GROUP", "SQL-HAVING", "SQL-SUBQUERY"}


def _tags(concept_codes, extra=()):
    tags = {"postgres"}
    for cc in concept_codes:
        area = _CONCEPT_AREA.get(cc)
        if area:
            tags.add(f"postgres:{_AREA_SLUG[area]}")
        tags.add(f"pg:{cc.lower()}")
    for t in extra:
        tags.add(t)
    return sorted(tags)


def M(qid, concept_code, diff, prompt, answer, d1, d2, d3, expl, srcs, extra_tags=()):
    """Register an MCQ. Correct option position rotates deterministically."""
    assert concept_code in _CONCEPTS, f"{qid}: unknown concept {concept_code}"
    opts = [answer, d1, d2, d3]
    rot = sum(bytearray(qid.encode())) % 4
    labels = ["A", "B", "C", "D"]
    order = [opts[(rot + i) % 4] for i in range(4)]
    correct = labels[order.index(answer)]
    MCQS.append({
        "id": qid, "concepts": [concept_code], "difficulty": diff,
        "prompt": prompt, "options": order, "correct": correct,
        "explanation": expl, "source_refs": refs(*srcs),
        "tags": _tags([concept_code], extra_tags), "points": 1,
        "answer": answer,  # kept for validation; builder strips it
    })


def S(qid, concepts, required, diff, prompt, ref, datasets, expl, srcs, extra_tags=()):
    for cc in concepts:
        assert cc in _CONCEPTS, f"{qid}: unknown concept {cc}"
    SQLS.append({
        "id": qid, "concepts": concepts, "required": required, "difficulty": diff,
        "prompt": prompt, "reference": ref, "datasets": datasets,
        "explanation": expl, "source_refs": refs(*srcs),
        "tags": _tags(concepts, extra_tags + ("postgres:sql",)),
    })


def rubric(points, excellent, good, fair, poor):
    """Canonical four-level rubric matching existing pack band boundaries."""
    return [
        {"label": "Incomplete", "min_score": 0, "max_score": round(points * 0.25 - 0.01, 2),
         "criteria": poor},
        {"label": "Partial", "min_score": round(points * 0.25, 2), "max_score": round(points * 0.5 - 0.01, 2),
         "criteria": fair},
        {"label": "Mostly Complete", "min_score": round(points * 0.5, 2), "max_score": round(points * 0.75 - 0.01, 2),
         "criteria": good},
        {"label": "Complete", "min_score": round(points * 0.75, 2), "max_score": points,
         "criteria": excellent},
    ]


def E(qid, concepts, diff, prompt, ref, bands, expl, srcs, points=5, extra_tags=()):
    for cc in concepts:
        assert cc in _CONCEPTS, f"{qid}: unknown concept {cc}"
    ESSAYS.append({
        "id": qid, "concepts": concepts, "difficulty": diff, "prompt": prompt,
        "reference": ref, "rubric": rubric(points, *bands), "points": points,
        "explanation": expl, "source_refs": refs(*srcs),
        "tags": _tags(concepts, extra_tags + ("postgres:essay",)),
    })


